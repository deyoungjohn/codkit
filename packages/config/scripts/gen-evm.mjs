/**
 * Regenerate src/evm-chains.ts from viem's chain definitions (dev-time only;
 * the package never imports viem at runtime). `pnpm --filter @codkit/config gen`
 */
import { writeFileSync } from "node:fs";
import * as all from "viem/chains";

// [our key, viem export, Alchemy network slug]
const CHAINS = [
  ["ethereum", "mainnet", "eth-mainnet"],
  ["sepolia", "sepolia", "eth-sepolia"],
  ["base", "base", "base-mainnet"],
  ["base-sepolia", "baseSepolia", "base-sepolia"],
  ["optimism", "optimism", "opt-mainnet"],
  ["optimism-sepolia", "optimismSepolia", "opt-sepolia"],
  ["arbitrum", "arbitrum", "arb-mainnet"],
  ["arbitrum-sepolia", "arbitrumSepolia", "arb-sepolia"],
  ["polygon", "polygon", "polygon-mainnet"],
  ["polygon-amoy", "polygonAmoy", "polygon-amoy"],
  ["bsc", "bsc", "bnb-mainnet"],
  ["bsc-testnet", "bscTestnet", "bnb-testnet"],
  ["avalanche", "avalanche", "avax-mainnet"],
  ["avalanche-fuji", "avalancheFuji", "avax-fuji"],
  ["celo", "celo", "celo-mainnet"],
  ["celo-alfajores", "celoAlfajores", "celo-alfajores"],
  ["linea-sepolia", "lineaSepolia", "linea-sepolia"],
  ["scroll-sepolia", "scrollSepolia", null], // no Alchemy endpoint (checked 2026-11-17)
  ["unichain-sepolia", "unichainSepolia", "unichain-sepolia"],
  ["monad-testnet", "monadTestnet", "monad-testnet"],
  ["anvil", "anvil", null],
];

const out = CHAINS.map(([key, name, alchemy]) => {
  // biome-ignore lint/performance/noDynamicNamespaceImportAccess: a dev-time generator, never bundled
  const c = all[name];
  if (!c) throw new Error(`viem/chains has no ${name}`);
  const explorer = c.blockExplorers?.default;
  return {
    key,
    id: `eip155:${c.id}`,
    ecosystem: "evm",
    name: c.name,
    testnet: key === "anvil" ? true : Boolean(c.testnet),
    chainId: c.id,
    nativeCurrency: c.nativeCurrency,
    rpcUrls: c.rpcUrls.default.http,
    ...(c.rpcUrls.default.webSocket?.length && { wsUrls: c.rpcUrls.default.webSocket }),
    ...(explorer && { explorer: { name: explorer.name, url: explorer.url.replace(/\/+$/, "") } }),
    ...(alchemy && { providers: { alchemy } }),
  };
});

const { version } = JSON.parse(
  await (await import("node:fs/promises")).readFile(new URL(import.meta.resolve("viem/package.json")), "utf8"),
);
writeFileSync(
  new URL("../src/evm-chains.ts", import.meta.url),
  `// Generated by scripts/gen-evm.mjs from viem ${version}. Do not edit by hand.\nimport type { ChainConfig } from "./types.js";\n\nexport const evmChains = ${JSON.stringify(out, null, 2)} as const satisfies readonly ChainConfig[];\n`,
);
console.log(`wrote ${out.length} EVM chains (viem ${version})`);
