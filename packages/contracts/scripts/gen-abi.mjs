// Regenerates src/evm/abi.ts from Foundry output. Run `pnpm abi` after changing contracts.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const contracts = ["Escrow", "Reputation", "ReceiptAnchor"];
let out = "// Generated by scripts/gen-abi.mjs from evm/out — do not edit.\n";
for (const name of contracts) {
  const art = JSON.parse(readFileSync(join(root, "evm/out", `${name}.sol`, `${name}.json`), "utf8"));
  const camel = name[0].toLowerCase() + name.slice(1);
  out += `\nexport const ${camel}Abi = ${JSON.stringify(art.abi, null, 2)} as const;\n`;
  out += `\nexport const ${camel}Bytecode = ${JSON.stringify(art.bytecode.object)} as const;\n`;
}
writeFileSync(join(root, "src/evm/abi.ts"), out);
console.log(`wrote src/evm/abi.ts (${contracts.join(", ")})`);
