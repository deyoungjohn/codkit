// Deployments registry: deployments/<name>.json (committed for public networks)
// and the generated src/deployments.ts that packages import.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

export const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "deployments");
const LOCAL = /(^|-)(local|localnet|anvil)\b/;

export function writeDeployment(name, data) {
  writeFileSync(join(dir, `${name}.json`), `${JSON.stringify(data, null, 2)}\n`);
  regenerate();
  console.log(`recorded deployments/${name}.json`);
}

export function readDeployment(name) {
  return JSON.parse(readFileSync(join(dir, `${name}.json`), "utf8"));
}

/** Rebuild src/deployments.ts from every public-network JSON file. */
export function regenerate() {
  const entries = readdirSync(dir)
    .filter((f) => f.endsWith(".json") && !LOCAL.test(f))
    .sort()
    .map((f) => [f.replace(/\.json$/, ""), JSON.parse(readFileSync(join(dir, f), "utf8"))]);
  const body = entries.map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v, null, 2).replace(/\n/g, "\n  ")},`).join("\n");
  writeFileSync(
    join(root, "src", "deployments.ts"),
    `// Generated by scripts/registry.mjs from deployments/*.json — do not edit.\n` +
      `// Public testnet deployments of the codkit contracts (local rehearsals are excluded).\n\n` +
      `export const deployments = {\n${body}\n} as const;\n\nexport type DeploymentName = keyof typeof deployments;\n`,
  );
}

if (import.meta.url === `file://${process.argv[1]}`) regenerate();
